"""Train neural Energy and Dissipation models with PyTorch Lightning.

The training data consists of OU paths used as e(t). Sigma targets are
generated by the reference discretization in ``xi_sigma.py``.
"""

from __future__ import annotations

import argparse

import lightning.pytorch as pl
import torch
from torch import Tensor, nn
from torch.utils.data import DataLoader, TensorDataset
from lightning.pytorch.plugins.environments import LightningEnvironment

from src.neural_variational_ode import Dissipation, Energy, VariationalODESolver
from src.ou_trajectories import generate_ou_trajectories
from src.xi_sigma import compute_xi_and_sigma
import numpy as np


class VariationalODELightningModule(pl.LightningModule):
    """Supervised trainer for the neural variational ODE."""

    def __init__(
        self,
        dt: float = 0.1,
        learning_rate: float = 1e-3,
        e_dim: int = 1,
        xi_dim: int = 1,
        target_xi_mean: float = 0.3,
        lagrange_lr: float = 1e-2,
        constraint_penalty: float = 1.0,
        use_lagrange_multiplier: bool = False,
    ) -> None:
        super().__init__()
        if lagrange_lr <= 0:
            raise ValueError("lagrange_lr must be positive.")
        if constraint_penalty < 0:
            raise ValueError("constraint_penalty must be non-negative.")
        self.save_hyperparameters()
        self.solver = VariationalODESolver(
            Energy(e_dim=e_dim, xi_dim=xi_dim), Dissipation(xi_dim=xi_dim)
        )
        self.loss = nn.MSELoss()
        self.register_buffer(
            "lagrange_multiplier", torch.zeros(xi_dim, dtype=torch.float32)
        )
        self.register_buffer(
            "target_xi_mean",
            torch.full((xi_dim,), target_xi_mean, dtype=torch.float32),
        )

    def forward(self, e_trajectories: Tensor) -> tuple[Tensor, Tensor]:
        return self.solver.solve(e_trajectories, dt=self.hparams.dt, create_graph=True)

    def training_step(
        self, batch: tuple[Tensor, Tensor, Tensor], batch_idx: int
    ) -> Tensor:
        e_trajectories, _, sigma_target = batch
        xi_predicted, sigma_predicted = self(e_trajectories)
        sigma_loss = self.loss(sigma_predicted, sigma_target)

        xi_for_mean = (
            xi_predicted.unsqueeze(-1) if xi_predicted.ndim == 2 else xi_predicted
        )
        xi_mean = xi_for_mean.mean(dim=(0, 1))
        mean_residual = xi_mean - self.target_xi_mean.to(xi_mean)
        penalty_loss = 0.5 * self.hparams.constraint_penalty * torch.sum(
            mean_residual.square()
        )
        if self.hparams.use_lagrange_multiplier:
            # The multiplier is a dual variable, not a neural-network parameter.
            # Clone it so the in-place dual update cannot alter this loss graph.
            dual_loss = torch.dot(
                self.lagrange_multiplier.detach().clone(), mean_residual
            )
        else:
            dual_loss = mean_residual.new_zeros(())
        total_loss = sigma_loss #+ penalty_loss + dual_loss

        if self.hparams.use_lagrange_multiplier:
            with torch.no_grad():
                self.lagrange_multiplier.add_(
                    self.hparams.lagrange_lr * mean_residual.detach()
                )

        self.log_dict(
            {
                "loss": total_loss,
                # "sigma_loss": sigma_loss,
                # "lagrange_loss": dual_loss,
                # "penalty_loss": penalty_loss,
            },
            on_step=False,
            on_epoch=True,
            prog_bar=True,
            batch_size=e_trajectories.shape[0],
        )
        return total_loss


    def configure_optimizers(self) -> torch.optim.Optimizer:
          return torch.optim.Adam(self.parameters(), lr=self.hparams.learning_rate)




def main() -> None:
    parser = argparse.ArgumentParser(description="Train neural variational ODE models.")
    parser.add_argument("--epochs", type=int, default=500)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--num-trajectories", type=int, default=512)
    parser.add_argument("--dt", type=float, default=1/500)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--target-xi-mean", type=float, default=1.0)
    parser.add_argument("--lagrange-lr", type=float, default=1e-4)
    parser.add_argument("--constraint-penalty", type=float, default=1.0)
    parser.add_argument(
        "--use-lagrange-multiplier",
        action="store_true",
        default=False,
        help="Enable the iterative Lagrange multiplier term in addition to the penalty.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--dataset-path", default="training_dataset.pt")
    parser.add_argument("--run_id", type=str)
    args = parser.parse_args()

    pl.seed_everything(torch.randint(0, 1000000, (1,))[0].item(), workers=True)
    # training_dataset = make_training_dataset(
    #     args.num_trajectories, args.dt, args.seed
    # )
    # save_training_dataset(training_dataset, args.dt, args.dataset_path)
    training_dataset = torch.load(args.dataset_path)
    training_dataset = TensorDataset(
        torch.as_tensor(training_dataset['e_trajectories'], dtype=torch.float32),
        torch.as_tensor(training_dataset['xi_target'], dtype=torch.float32),
        torch.as_tensor(training_dataset['sigma_target'], dtype=torch.float32),
    )
    train_loader = DataLoader(training_dataset, batch_size=args.batch_size, shuffle=True)
    model = VariationalODELightningModule(
        dt=args.dt,
        learning_rate=args.learning_rate,
        e_dim=1,
        xi_dim=1,
        target_xi_mean=args.target_xi_mean,
        lagrange_lr=args.lagrange_lr,
        constraint_penalty=args.constraint_penalty,
        use_lagrange_multiplier=args.use_lagrange_multiplier,
    )
    trainer = pl.Trainer(
        max_epochs=args.epochs,
        accelerator="cpu",
        devices=1,
        plugins=[LightningEnvironment()],
        logger=False,
        enable_checkpointing=False,
    )
    trainer.fit(model, train_dataloaders=train_loader)
    torch.save(model.solver.state_dict(), f"neural_variational_ode_{args.run_id}.pt")


if __name__ == "__main__":
    main()
